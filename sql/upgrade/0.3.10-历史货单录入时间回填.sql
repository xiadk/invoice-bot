-- v0.3.10 历史货单「录入时间」回填
--
-- 背景：v0.3.6 导入「进货单留存.xlsx」时没有指定 created_at，357 张历史货单全部取
--       数据库默认值 CURRENT_TIMESTAMP —— 也就是导入那一刻（2026-11-03 11:19~12:23）。
--       而 v0.3.10 起，员工账号在「货单管理」只看得到最近 7 天**录入**（created_at）的
--       货单、且不给看合计金额。若不回填：
--         · 员工现在会看到全部 357 张（都是今天录入的），限制形同虚设；
--         · 2026-11-10 之后这 357 张会在同一天集体掉出窗口，员工看到 0 张。
--       用户 2026-11-03 确认：历史数据的 created_at 回填为各自的**货单日期**（时分置 12:00），
--       因为这些单本来就是按货单日期补录的，导入时刻没有任何业务含义。
--
-- 影响：
--   · 只改 note 以「Excel导入」开头的行（历史上唯一的批量导入来源，也是幂等键/图片锚点），
--     手工新建的货单不受影响；
--   · 「新建日期」列对这些历史行会显示货单日期（对补录数据更真实）；
--   · 不删不插，金额/供应商/开票状态/图片绑定全部不动。
--
-- 执行：mysql -u<user> -p<pwd> <db> < sql/upgrade/0.3.10-历史货单录入时间回填.sql
--       幂等：条件 DATE(created_at) <> bill_date，重复执行不会反复改写
--
-- 回滚：无法还原到「导入时刻」（该值已丢失）。
--       若只是想让员工看到全部，把 v0.3.10 的 restrictDays 逻辑去掉即可，不要靠改这里。
--
-- 核对：SELECT COUNT(*) FROM waybill
--        WHERE note LIKE 'Excel导入%' AND DATE(created_at) <> bill_date;   -- 应为 0
--       SELECT DATE(created_at) d, COUNT(*) n FROM waybill
--        WHERE note LIKE 'Excel导入%' GROUP BY 1 ORDER BY 1;               -- 应与 bill_date 分布一致
-- ----------------------------------------------------------------------------

UPDATE `waybill`
   SET `created_at` = TIMESTAMP(`bill_date`, '12:00:00')
 WHERE `note` LIKE 'Excel导入%'
   AND DATE(`created_at`) <> `bill_date`;
